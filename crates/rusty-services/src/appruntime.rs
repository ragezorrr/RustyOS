//! Application process runtime isolation (`systemd --user` transient scopes),
//! Chromium/Electron native Wayland flag injection, XDG user directory bootstrap,
//! and default MIME association setup (`RUSTYOS-155`, ADR-0084).

use std::env;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Standard XDG user directories created idempotently on session startup.
pub const DEFAULT_XDG_USER_SUBDIRS: &[&str] = &[
    "Desktop",
    "Documents",
    "Downloads",
    "Music",
    "Pictures",
    "Pictures/Screenshots",
    "Videos",
];

/// Canonical content of `~/.config/user-dirs.dirs` written when missing.
pub const DEFAULT_USER_DIRS_CONFIG: &str = "\
# Generated by RustyOS session runtime (RUSTYOS-155)
XDG_DESKTOP_DIR=\"$HOME/Desktop\"
XDG_DOWNLOAD_DIR=\"$HOME/Downloads\"
XDG_TEMPLATES_DIR=\"$HOME\"
XDG_PUBLICSHARE_DIR=\"$HOME\"
XDG_DOCUMENTS_DIR=\"$HOME/Documents\"
XDG_MUSIC_DIR=\"$HOME/Music\"
XDG_PICTURES_DIR=\"$HOME/Pictures\"
XDG_VIDEOS_DIR=\"$HOME/Videos\"
";

/// Canonical content of `rustyos-mimeapps.list` associating folders and core types with RustyOS apps.
pub const DEFAULT_RUSTYOS_MIMEAPPS_LIST: &str = "\
[Default Applications]
inode/directory=org.rustyos.files.desktop;
x-scheme-handler/file=org.rustyos.files.desktop;

[Added Associations]
inode/directory=org.rustyos.files.desktop;
x-scheme-handler/file=org.rustyos.files.desktop;
";

/// Chromium and Electron binary basenames that benefit from automatic native Wayland Ozone flags.
const WAYLAND_CHROMIUM_ELECTRON_BINARIES: &[&str] = &[
    "chromium",
    "chromium-browser",
    "google-chrome",
    "google-chrome-stable",
    "google-chrome-beta",
    "google-chrome-unstable",
    "brave",
    "brave-browser",
    "vivaldi",
    "vivaldi-stable",
    "microsoft-edge",
    "microsoft-edge-stable",
    "opera",
    "electron",
    "code",
    "code-oss",
    "codium",
    "vscodium",
    "cursor",
    "windsurf",
    "discord",
    "vesktop",
    "slack",
    "obsidian",
    "spotify",
];

/// Returns `true` if `program` refers to a known Chromium or Electron application binary.
#[must_use]
pub fn is_chromium_or_electron_binary(program: &Path) -> bool {
    let Some(name) = program.file_name().and_then(|s| s.to_str()) else {
        return false;
    };
    let lower = name.trim().to_ascii_lowercase();
    WAYLAND_CHROMIUM_ELECTRON_BINARIES.contains(&lower.as_str())
        || lower.starts_with("electron")
            && lower[8..].chars().all(|c| c.is_ascii_digit() || c == '-')
}

/// Appends `--ozone-platform-hint=auto` and `--enable-features=WaylandWindowDecorations`
/// for Chromium/Electron binaries unless the user or `.desktop` entry already specified
/// an explicit `--ozone-platform` flag.
#[must_use]
pub fn inject_wayland_browser_flags(program: &Path, args: &[String]) -> Vec<String> {
    let mut out = args.to_vec();
    if !is_chromium_or_electron_binary(program) {
        return out;
    }
    let has_ozone_flag = out.iter().any(|arg| {
        arg.starts_with("--ozone-platform=") || arg.starts_with("--ozone-platform-hint=")
    });
    if !has_ozone_flag {
        out.push("--ozone-platform-hint=auto".to_owned());
    }
    let has_wayland_decorations = out
        .iter()
        .any(|arg| arg.contains("WaylandWindowDecorations"));
    if !has_wayland_decorations {
        out.push("--enable-features=WaylandWindowDecorations".to_owned());
    }
    out
}

/// Sanitizes an executable path or basename into a lowercase `systemd` unit identifier segment
/// (`[a-z0-9]+` separated by single hyphens, max 32 chars).
#[must_use]
pub fn sanitize_systemd_app_id(program: &Path) -> String {
    let raw = program
        .file_name()
        .and_then(|s| s.to_str())
        .map_or("app", |name| name.strip_suffix(".desktop").unwrap_or(name));
    let mut sanitized = String::with_capacity(raw.len().min(32));
    let mut prev_hyphen = false;
    for ch in raw.chars() {
        let lower = ch.to_ascii_lowercase();
        if lower.is_ascii_alphanumeric() {
            sanitized.push(lower);
            prev_hyphen = false;
        } else if !sanitized.is_empty() && !prev_hyphen {
            sanitized.push('-');
            prev_hyphen = true;
        }
        if sanitized.len() >= 32 {
            break;
        }
    }
    while sanitized.ends_with('-') {
        sanitized.pop();
    }
    if sanitized.is_empty() {
        "app".to_owned()
    } else {
        sanitized
    }
}

/// Checks whether `systemd --user` transient scopes can be spawned in the current environment.
///
/// Requires `XDG_RUNTIME_DIR/systemd/private` to exist and `/usr/bin/systemd-run` (or
/// `/bin/systemd-run`) to be present, and `RUSTYOS_DISABLE_SYSTEMD_SCOPES` not set to `1`.
#[must_use]
pub fn is_systemd_user_scope_available() -> bool {
    if env::var_os("RUSTYOS_DISABLE_SYSTEMD_SCOPES")
        .is_some_and(|v| v == "1" || v.eq_ignore_ascii_case("true"))
    {
        return false;
    }
    let Some(runtime_dir) = env::var_os("XDG_RUNTIME_DIR") else {
        return false;
    };
    if !Path::new(&runtime_dir).join("systemd/private").exists() {
        return false;
    }
    systemd_run_binary_path().is_some()
}

fn systemd_run_binary_path() -> Option<PathBuf> {
    for candidate in ["/usr/bin/systemd-run", "/bin/systemd-run"] {
        let path = Path::new(candidate);
        if path.is_file() {
            return Some(path.to_path_buf());
        }
    }
    None
}

/// Constructs the command and argument vector for launching `program`, wrapping it in
/// `systemd-run --user --scope --quiet --collect --unit=app-rustyos-<appid>-<seq>.scope --`
/// when `use_systemd_scope` is `true`, or returning `(program, injected_args)` directly as a
/// zero-overhead fallback.
#[must_use]
pub fn build_scoped_launch_command(
    program: &Path,
    args: &[String],
    seq: u64,
    use_systemd_scope: bool,
) -> (PathBuf, Vec<String>) {
    let effective_args = inject_wayland_browser_flags(program, args);
    if !use_systemd_scope {
        return (program.to_path_buf(), effective_args);
    }

    let systemd_run =
        systemd_run_binary_path().unwrap_or_else(|| PathBuf::from("/usr/bin/systemd-run"));
    let app_id = sanitize_systemd_app_id(program);
    let unit_name = format!("app-rustyos-{app_id}-{seq}.scope");

    let mut scoped_args = Vec::with_capacity(7 + effective_args.len());
    scoped_args.push("--user".to_owned());
    scoped_args.push("--scope".to_owned());
    scoped_args.push("--quiet".to_owned());
    scoped_args.push("--collect".to_owned());
    scoped_args.push(format!("--unit={unit_name}"));
    scoped_args.push("--".to_owned());
    scoped_args.push(program.to_string_lossy().into_owned());
    scoped_args.extend(effective_args);

    (systemd_run, scoped_args)
}

/// Idempotently creates the standard XDG user directories under `home` and writes
/// `config_home/user-dirs.dirs` if it does not already exist.
///
/// # Errors
///
/// Returns an [`io::Error`] if directory creation or writing `user-dirs.dirs` fails.
pub fn ensure_xdg_user_directories(home: &Path, config_home: &Path) -> io::Result<()> {
    for rel in DEFAULT_XDG_USER_SUBDIRS {
        fs::create_dir_all(home.join(rel))?;
    }
    fs::create_dir_all(config_home)?;
    let user_dirs_file = config_home.join("user-dirs.dirs");
    if !user_dirs_file.exists() {
        fs::write(&user_dirs_file, DEFAULT_USER_DIRS_CONFIG)?;
    }
    let locale_file = config_home.join("user-dirs.locale");
    if !locale_file.exists() {
        let _ = fs::write(&locale_file, "UTF-8\n");
    }
    Ok(())
}

/// Idempotently writes `config_home/rustyos-mimeapps.list` so `XDG_CURRENT_DESKTOP=RustyOS`
/// resolves `inode/directory` and `x-scheme-handler/file` to `org.rustyos.files.desktop`.
///
/// # Errors
///
/// Returns an [`io::Error`] if creating `config_home` or writing `rustyos-mimeapps.list` fails.
pub fn ensure_rustyos_mimeapps_list(config_home: &Path) -> io::Result<()> {
    fs::create_dir_all(config_home)?;
    let mimeapps_path = config_home.join("rustyos-mimeapps.list");
    if !mimeapps_path.exists() {
        fs::write(&mimeapps_path, DEFAULT_RUSTYOS_MIMEAPPS_LIST)?;
    }
    Ok(())
}

/// Bootstraps XDG user directories and `rustyos-mimeapps.list` for the current user session.
///
/// Safe to call on compositor startup; silently no-ops if `$HOME` is unset.
///
/// # Errors
///
/// Returns an [`io::Error`] if creating the XDG user directories or writing `user-dirs.dirs` /
/// `rustyos-mimeapps.list` fails.
pub fn bootstrap_user_session_environment() -> io::Result<()> {
    let Some(home) = env::var_os("HOME").map(PathBuf::from) else {
        return Ok(());
    };
    let config_home =
        env::var_os("XDG_CONFIG_HOME").map_or_else(|| home.join(".config"), PathBuf::from);
    ensure_xdg_user_directories(&home, &config_home)?;
    ensure_rustyos_mimeapps_list(&config_home)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn unique_temp_dir(label: &str) -> io::Result<PathBuf> {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |d| d.as_nanos());
        let dir = env::temp_dir().join(format!(
            "rustyos-appruntime-{label}-{}-{nanos}",
            std::process::id()
        ));
        fs::create_dir_all(&dir)?;
        Ok(dir)
    }

    #[test]
    fn injects_wayland_flags_for_chromium_and_electron_binaries() {
        let args = vec!["--new-window".to_owned(), "https://example.com".to_owned()];
        let injected = inject_wayland_browser_flags(Path::new("/usr/bin/chromium"), &args);
        assert!(injected.contains(&"--ozone-platform-hint=auto".to_owned()));
        assert!(injected.contains(&"--enable-features=WaylandWindowDecorations".to_owned()));

        let code_injected = inject_wayland_browser_flags(Path::new("/usr/bin/code"), &[]);
        assert_eq!(
            code_injected,
            vec![
                "--ozone-platform-hint=auto".to_owned(),
                "--enable-features=WaylandWindowDecorations".to_owned()
            ]
        );
    }

    #[test]
    fn does_not_inject_duplicate_or_non_browser_wayland_flags() {
        let native_args = vec!["--pick-file".to_owned()];
        let untouched =
            inject_wayland_browser_flags(Path::new("/usr/bin/rusty-files"), &native_args);
        assert_eq!(untouched, native_args);

        let custom_ozone = vec!["--ozone-platform=x11".to_owned()];
        let preserved =
            inject_wayland_browser_flags(Path::new("/usr/bin/google-chrome-stable"), &custom_ozone);
        assert_eq!(
            preserved,
            vec![
                "--ozone-platform=x11".to_owned(),
                "--enable-features=WaylandWindowDecorations".to_owned()
            ]
        );
    }

    #[test]
    fn builds_systemd_user_scope_command_and_direct_fallback() {
        let prog = Path::new("/usr/bin/rusty-terminal");
        let args = vec!["-e".to_owned(), "htop".to_owned()];

        let (direct_bin, direct_args) = build_scoped_launch_command(prog, &args, 7, false);
        assert_eq!(direct_bin, prog);
        assert_eq!(direct_args, args);

        let (scoped_bin, scoped_args) = build_scoped_launch_command(prog, &args, 42, true);
        assert!(scoped_bin.ends_with("systemd-run"));
        assert_eq!(scoped_args[0], "--user");
        assert_eq!(scoped_args[1], "--scope");
        assert_eq!(scoped_args[2], "--quiet");
        assert_eq!(scoped_args[3], "--collect");
        assert_eq!(scoped_args[4], "--unit=app-rustyos-rusty-terminal-42.scope");
        assert_eq!(scoped_args[5], "--");
        assert_eq!(scoped_args[6], "/usr/bin/rusty-terminal");
        assert_eq!(&scoped_args[7..], &args[..]);
    }

    #[test]
    fn sanitizes_systemd_app_ids() {
        assert_eq!(
            sanitize_systemd_app_id(Path::new("/usr/bin/org.rustyos.Files_v2!")),
            "org-rustyos-files-v2"
        );
        assert_eq!(sanitize_systemd_app_id(Path::new("---")), "app");
    }

    #[test]
    fn creates_xdg_user_directories_and_rustyos_mimeapps_list_idempotently() -> io::Result<()> {
        let root = unique_temp_dir("xdg-bootstrap")?;
        let home = root.join("home");
        let config = home.join(".config");

        ensure_xdg_user_directories(&home, &config)?;
        ensure_rustyos_mimeapps_list(&config)?;

        for sub in DEFAULT_XDG_USER_SUBDIRS {
            assert!(home.join(sub).is_dir(), "expected subdir {sub} to exist");
        }
        let user_dirs = fs::read_to_string(config.join("user-dirs.dirs"))?;
        assert!(user_dirs.contains("XDG_PICTURES_DIR=\"$HOME/Pictures\""));

        let mimeapps = fs::read_to_string(config.join("rustyos-mimeapps.list"))?;
        assert!(mimeapps.contains("inode/directory=org.rustyos.files.desktop;"));

        let _ = fs::remove_dir_all(&root);
        Ok(())
    }
}
